"""Shared helpers for the docs generators.

The generators parse source files with ``ast`` and YAML. They never import
the code they describe, so they run without the server's dependencies.
"""

import ast
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
DESCRIPTIONS = REPO / "scripts" / "docs" / "descriptions.yml"
CODE_ROOTS = ("api", "common", "conserver")
TODO = "TODO(verify)"


def rel(path):
    return path.relative_to(REPO).as_posix()


def is_test_file(path):
    parts = path.relative_to(REPO).parts
    return (
        "tests" in parts
        or "test" in parts
        or path.name.startswith("test_")
        or path.name.endswith("_test.py")
        or path.name == "conftest.py"
    )


def iter_python_files():
    """Yield non-test Python files under the code roots in a stable order."""
    for root in CODE_ROOTS:
        for path in sorted((REPO / root).rglob("*.py")):
            if not is_test_file(path):
                yield path


def parse(path):
    """Parse a Python file and give every node a ``parent`` attribute."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            child.parent = node
    return tree


def call_name(node):
    """Return the bare function name of a Call node, or an empty string."""
    if isinstance(node.func, ast.Name):
        return node.func.id
    if isinstance(node.func, ast.Attribute):
        return node.func.attr
    return ""


def keyword(call, name):
    for item in call.keywords:
        if item.arg == name:
            return item.value
    return None


def constant(node):
    """Return a node's constant value, or None when it has none."""
    return node.value if isinstance(node, ast.Constant) else None


def load_section(section):
    """Return one top-level section of descriptions.yml."""
    data = yaml.safe_load(DESCRIPTIONS.read_text(encoding="utf-8")) or {}
    block = data.get(section) or {}
    block.setdefault("entries", {})
    return block


def check_stale(section, block, known):
    """Fail when descriptions.yml names something the code no longer has."""
    stale = sorted(set(block["entries"]) - set(known))
    if stale:
        sys.exit(
            f"descriptions.yml section {section!r} has entries the code no "
            f"longer provides: {', '.join(stale)}"
        )


def entry(block, key):
    """Return an entry as a dict, accepting a bare string as the description."""
    value = block["entries"].get(key)
    if value is None:
        return {}
    if isinstance(value, str):
        return {"description": value}
    return value


def description(block, key, required=True):
    text = str(entry(block, key).get("description", "")).strip()
    if not text and required:
        print(f"warning: no description for {key}", file=sys.stderr)
        return TODO
    return text


def cell(text):
    """Make text safe for a Markdown table cell."""
    return " ".join(str(text).split()).replace("|", "\\|")


def code(text):
    return f"`{text}`"


def table(headers, rows):
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    lines += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def write_page(filename, title, generator, block, sections):
    """Write a generated page under docs/reference/."""
    parts = [
        f"<!-- Generated by scripts/docs/{generator}. Do not edit by hand. -->",
        f"# {title}",
        '!!! note "Generated page"\n'
        f"    `scripts/docs/{generator}` builds this page from the code. "
        "Text that needs a person lives in `scripts/docs/descriptions.yml`. "
        "Edit that file, not this page.",
    ]
    for piece in [block.get("intro"), *sections, block.get("outro")]:
        if piece and str(piece).strip():
            parts.append(str(piece).strip())
    target = REPO / "docs" / "reference" / filename
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {rel(target)}")
